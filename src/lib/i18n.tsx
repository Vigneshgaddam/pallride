const map: Record<string, string> = {};
Object.values(DICT).flat().forEach(([en, te]) => (map[en] = te));

const LangCtx = createContext<{ te: boolean; toggle: () => void }>({ te: false, toggle: () => {} });

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [te, setTe] = useState(false);
  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect -- sync persisted lang after mount (SSR-safe)
    setTe(localStorage.getItem("pr_lang") === "te");
  }, []);
  const toggle = () => {
    const n = !te;
    setTe(n);
    localStorage.setItem("pr_lang", n ? "te" : "en");
    document.documentElement.lang = n ? "te" : "en";
  };
  return <LangCtx.Provider value={{ te, toggle }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  return useContext(LangCtx);
}

export function useT() {
  const { te } = useLang();
  return (en: string) => (te ? map[en] || en : en);
}
